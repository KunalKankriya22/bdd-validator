import {
  Component,
  EventEmitter,
  Input,
  OnInit,
  OnChanges,
  OnDestroy,
  SimpleChanges,
  Output,
  ChangeDetectionStrategy,
  ChangeDetectorRef,
  signal,
  computed
} from '@angular/core';
import { CommonModule } from '@angular/common';
import { FormBuilder, FormGroup, FormControl, Validators, ReactiveFormsModule, AsyncValidatorFn } from '@angular/forms';
import { MatSelectModule } from '@angular/material/select';
import { MatInputModule } from '@angular/material/input';
import { MatFormFieldModule } from '@angular/material/form-field';
import { MatButtonModule } from '@angular/material/button';
import { NgxMatSelectSearchModule } from 'ngx-mat-select-search';
import { Subject, takeUntil, debounceTime } from 'rxjs';
import { ProcessMappingDto } from '../../interfaces/process-mapping.interface';
import { ManufLookupService } from '../../services/manuf-lookup.service';
import { SqlEditorComponent } from '@shared/components/sql-editor/sql-editor.component';
import { ProcessMappingService } from '../../services/process-mapping.service';
import {
  columnRequiresTableValidator,
  tableColumnConsistencyValidator,
  duplicateMappingNameValidator,
  validTableNameValidator,
  validColumnNameValidator,
  maxLengthWithMessage,
  requiredNonWhitespace,
  getErrorMessage
} from '../../validators/emf-mapping.validators';

export interface MappingDetailPayload {
  mappingName: string;
  dataTableName?: string;
  dataColumnName?: string;
  whereClause?: string;
  sqlStmt?: string;
}

@Component({
  selector: 'app-mapping-detail-panel',
  standalone: true,
  imports: [
    CommonModule,
    ReactiveFormsModule,
    MatSelectModule,
    MatInputModule,
    MatFormFieldModule,
    MatButtonModule,
    NgxMatSelectSearchModule,
    SqlEditorComponent
  ],
  templateUrl: './mapping-detail-panel.html',
  styleUrls: ['./mapping-detail-panel.scss'],
  changeDetection: ChangeDetectionStrategy.OnPush
})
export class MappingDetailPanel implements OnInit, OnChanges, OnDestroy {
  @Input() mode: 'add' | 'edit' = 'add';
  @Input() editData: ProcessMappingDto | null = null;
  @Input() processCode: string = '';
  @Output() save = new EventEmitter<MappingDetailPayload>();
  @Output() saveAndCreateAnother = new EventEmitter<MappingDetailPayload>();
  @Output() clearAll = new EventEmitter<void>();
  @Output() cancel = new EventEmitter<void>();

  form!: FormGroup;
  getErrorMessage = getErrorMessage;

  tableOptions = signal<string[]>([]);
  columnOptions = signal<string[]>([]);
  isLoadingTables = signal(false);
  isLoadingColumns = signal(false);

  // Search controls for dropdowns
  readonly tableSearchControl = new FormControl('');
  readonly columnSearchControl = new FormControl('');

  // Search signals
  readonly tableSearch = signal('');
  readonly columnSearch = signal('');

  // Filtered options
  readonly filteredTableOptions = computed(() => {
    const search = this.tableSearch().toLowerCase();
    const options = this.tableOptions();
    if (!search) return options;
    return options.filter(table => table.toLowerCase().includes(search));
  });

  readonly filteredColumnOptions = computed(() => {
    const search = this.columnSearch().toLowerCase();
    const options = this.columnOptions();
    if (!search) return options;
    return options.filter(column => column.toLowerCase().includes(search));
  });

  private destroy$ = new Subject<void>();
  private initialFormValue: any = null;

  get autoGeneratedSql(): string {
    const table = this.form?.get('dataTableName')?.value || '';
    const where = this.form?.get('whereClause')?.value?.trim() || '';
    if (!table) return '';
    let sql = `SELECT *\nFROM ${table}`;
    if (where) sql += `\nWHERE ${where}`;
    return sql;
  }

  get isSaveDisabled(): boolean {
    const isInvalid = this.form?.invalid ?? true;
    const isPending = this.form?.pending ?? false;

    // In edit mode, also check if form has changed
    if (this.mode === 'edit') {
      return isInvalid || isPending || !this.hasFormChanged();
    }

    // In add mode, only check validity
    return isInvalid || isPending;
  }

  private hasFormChanged(): boolean {
    if (!this.form || !this.initialFormValue) return false;

    const currentValue = this.form.getRawValue();
    return JSON.stringify(currentValue) !== JSON.stringify(this.initialFormValue);
  }

  /**
   * Get error message for a specific field
   * Returns empty string if field is valid or untouched
   */
  getFieldError(fieldName: string): string {
    const field = this.form?.get(fieldName);
    if (!field) return '';

    // Don't show error if field is not touched/dirty or if it's still pending validation
    if ((!field.touched && !field.dirty) || field.pending) {
      return '';
    }

    // Check specific field errors
    const errors = field.errors;
    if (!errors) {
      return '';
    }

    // Field-specific error messages
    switch (fieldName) {
      case 'mappingName':
        if (errors['required']) return 'Mapping Name is required';
        if (errors['duplicateMappingName']) return 'This mapping name already exists for this process code';
        break;

      case 'dataTableName':
        if (errors['invalidTableName']) return 'Invalid table name or not accessible in allowed schemas (SBCSYS, DONSYS, UTIL, SRVSYS, LTAPI, LTWEB, VISTA)';
        break;

      case 'dataColumnName':
        if (errors['columnWithoutTable']) return 'Table name must be specified before column';
        if (errors['tableWithoutColumn']) return 'Column name must be specified when table is selected';
        if (errors['invalidColumnName']) return 'Invalid column name for the specified table';
        break;

      case 'sqlStmt':
        if (errors['maxLengthExceeded']) return 'SQL Statement cannot exceed 2000 characters';
        break;
    }

    // Fallback to generic error message
    return getErrorMessage(errors);
  }

  constructor(
    private fb: FormBuilder,
    private cdr: ChangeDetectorRef,
    private lookupService: ManufLookupService,
    private mappingService: ProcessMappingService
  ) {
    // Subscribe to search control changes - immediately remove leading and trailing spaces
    this.tableSearchControl.valueChanges
      .pipe(takeUntil(this.destroy$))
      .subscribe(value => {
        const trimmedValue = value ? value.trim() : '';

        // Immediately update the control if there are leading or trailing spaces
        if (value && (value.startsWith(' ') || value.endsWith(' '))) {
          this.tableSearchControl.setValue(trimmedValue, { emitEvent: false });
        }

        this.tableSearch.set(trimmedValue);
      });

    this.columnSearchControl.valueChanges
      .pipe(takeUntil(this.destroy$))
      .subscribe(value => {
        const trimmedValue = value ? value.trim() : '';

        // Immediately update the control if there are leading or trailing spaces
        if (value && (value.startsWith(' ') || value.endsWith(' '))) {
          this.columnSearchControl.setValue(trimmedValue, { emitEvent: false });
        }

        this.columnSearch.set(trimmedValue);
      });
  }

  ngOnInit(): void {
    this.buildForm();
    this.loadTableNames();
  }

  ngOnChanges(changes: SimpleChanges): void {
    if (changes['editData'] && this.form) {
      if (this.editData === null && this.mode === 'add') {
        // Reset form completely after successful "Add and Create Another"
        this.resetForm();
      } else {
        this.patchForm();
      }
    }
  }

  ngOnDestroy(): void {
    this.destroy$.next();
    this.destroy$.complete();
  }

  private loadTableNames(): void {
    this.isLoadingTables.set(true);
    this.lookupService.getTableNames()
      .pipe(takeUntil(this.destroy$))
      .subscribe({
        next: (tables) => {
          this.tableOptions.set(tables);
          this.isLoadingTables.set(false);
          this.cdr.markForCheck();
        },
        error: () => {
          this.isLoadingTables.set(false);
          this.cdr.markForCheck();
        }
      });
  }

  private loadColumnNames(tableName: string): void {
    if (!tableName) {
      this.columnOptions.set([]);
      return;
    }

    this.isLoadingColumns.set(true);
    this.lookupService.getColumnNames(tableName)
      .pipe(takeUntil(this.destroy$))
      .subscribe({
        next: (columns) => {
          this.columnOptions.set(columns);
          this.isLoadingColumns.set(false);
          this.cdr.markForCheck();
        },
        error: () => {
          this.isLoadingColumns.set(false);
          this.cdr.markForCheck();
        }
      });
  }

  private buildForm(): void {
    // Create validators - use requiredNonWhitespace to reject whitespace-only strings
    const mappingNameValidators = [requiredNonWhitespace()];

    const mappingNameAsyncValidators: AsyncValidatorFn[] = [];

    // Add duplicate check validator
    if (this.processCode) {
      mappingNameAsyncValidators.push(
        duplicateMappingNameValidator(
          (procCode: string, mapName: string, origName?: string) =>
            this.mappingService.checkDuplicateMappingName(procCode, mapName, origName),
          this.processCode,
          this.editData?.mappingName
        )
      );
    }

    this.form = this.fb.group({
      mappingName: [
        this.editData?.mappingName ?? '',
        mappingNameValidators,
        mappingNameAsyncValidators
      ],
      dataTableName: [
        this.editData?.dataTableName ?? '',
        [],
        [validTableNameValidator((tableName: string) => this.lookupService.validateTableName(tableName))]
      ],
      dataColumnName: [
        this.editData?.dataColumnName ?? '',
        [columnRequiresTableValidator()]
      ],
      whereClause: [
        this.editData?.whereClause ?? '',
        []
      ],
      sqlStmt: [
        this.editData?.sqlStmt ?? '',
        [maxLengthWithMessage(2000, 'SQL Statement')]
      ]
    });

    if (this.editData?.dataTableName) {
      this.loadColumnNames(this.editData.dataTableName);
    }

    // Force Mapping Name to uppercase
    this.form.get('mappingName')?.valueChanges
      .pipe(takeUntil(this.destroy$))
      .subscribe(val => {
        if (val && val !== val.toUpperCase()) {
          this.form.get('mappingName')?.setValue(val.toUpperCase(), { emitEvent: false });
        }
      });

    // Re-validate when table name changes
    this.form.get('dataTableName')?.valueChanges
      .pipe(
        takeUntil(this.destroy$),
        debounceTime(300)
      )
      .subscribe(val => {
        const columnControl = this.form.get('dataColumnName');

        // Load columns for the new table
        this.loadColumnNames(val);

        // Clear column value and update its async validator
        columnControl?.setValue('');

        // Update column validator with new table
        if (val) {
          columnControl?.setAsyncValidators([
            validColumnNameValidator(
              (tableName: string, columnName: string) => this.lookupService.validateColumnName(tableName, columnName),
              this.form.get('dataTableName')
            )
          ]);
        } else {
          columnControl?.clearAsyncValidators();
        }

        // Revalidate column to trigger columnRequiresTable validator
        columnControl?.updateValueAndValidity();
        this.form.updateValueAndValidity();
        this.cdr.markForCheck();
      });

    // Re-validate when column name changes
    this.form.get('dataColumnName')?.valueChanges
      .pipe(
        takeUntil(this.destroy$),
        debounceTime(300)
      )
      .subscribe(() => {
        this.form.updateValueAndValidity();
        this.cdr.markForCheck();
      });

    // Re-validate when SQL statement changes
    this.form.get('sqlStmt')?.valueChanges
      .pipe(takeUntil(this.destroy$))
      .subscribe(() => {
        this.form.updateValueAndValidity();
        this.cdr.markForCheck();
      });

    this.form.valueChanges
      .pipe(takeUntil(this.destroy$))
      .subscribe(() => {
        this.cdr.markForCheck();
      });

    // Store initial form value for change tracking
    this.initialFormValue = this.form.getRawValue();
  }

  private patchForm(): void {
    // Use emitEvent: false to prevent the debounced dataTableName.valueChanges
    // subscription from clearing the column value via columnControl.setValue('')
    this.form.patchValue({
      mappingName: this.editData?.mappingName ?? '',
      dataTableName: this.editData?.dataTableName ?? '',
      dataColumnName: this.editData?.dataColumnName ?? '',
      whereClause: this.editData?.whereClause ?? '',
      sqlStmt: this.editData?.sqlStmt ?? ''
    }, { emitEvent: false });

    if (this.editData?.dataTableName) {
      this.loadColumnNames(this.editData.dataTableName);
      const columnControl = this.form.get('dataColumnName');
      columnControl?.setAsyncValidators([
        validColumnNameValidator(
          (tableName: string, columnName: string) => this.lookupService.validateColumnName(tableName, columnName),
          this.form.get('dataTableName')
        )
      ]);
      columnControl?.markAsPristine();
      columnControl?.markAsUntouched();
    } else {
      this.columnOptions.set([]);
      const columnControl = this.form.get('dataColumnName');
      columnControl?.clearAsyncValidators();
      columnControl?.updateValueAndValidity({ emitEvent: false });
    }

    this.form.updateValueAndValidity({ emitEvent: false });

    // Update initial form value for change tracking
    this.initialFormValue = this.form.getRawValue();
    this.cdr.markForCheck();
  }

  private resetForm(): void {
    this.form.reset({ mappingName: '', dataTableName: '', dataColumnName: '', whereClause: '', sqlStmt: '' });
    this.form.markAsUntouched();
    this.form.markAsPristine();
    this.columnOptions.set([]);
    this.tableSearchControl.reset('');
    this.columnSearchControl.reset('');

    // Update initial form value for change tracking
    this.initialFormValue = this.form.getRawValue();
    this.cdr.markForCheck();
  }

  /**
   * Prevent leading spaces from being typed in text fields
   */
  onFieldKeyDown(event: KeyboardEvent): void {
    if (event.key === ' ' || event.code === 'Space') {
      const input = event.target as HTMLInputElement | HTMLTextAreaElement;
      const cursorPosition = input.selectionStart || 0;

      // Prevent leading space (cursor at position 0)
      if (cursorPosition === 0) {
        event.preventDefault();
        return;
      }
    }
  }

  onCancel(): void {
    this.cancel.emit();
  }

  onClearAll(): void {
    this.form.reset({ mappingName: '', dataTableName: '', dataColumnName: '', whereClause: '', sqlStmt: '' });
    this.form.markAsUntouched();
    this.columnOptions.set([]);

    // Update initial form value for change tracking
    this.initialFormValue = this.form.getRawValue();
    this.clearAll.emit();
    this.cdr.markForCheck();
  }

  onAdd(): void {
    if (this.form.invalid) { this.form.markAllAsTouched(); this.cdr.markForCheck(); return; }

    // Trim all text fields before emitting
    const payload = this.form.value;
    if (payload.mappingName) {
      payload.mappingName = payload.mappingName.trim().toUpperCase();
    }
    if (payload.dataTableName) {
      payload.dataTableName = payload.dataTableName.trim();
    }
    if (payload.dataColumnName) {
      payload.dataColumnName = payload.dataColumnName.trim();
    }
    if (payload.whereClause) {
      payload.whereClause = payload.whereClause.trim();
    }
    if (payload.sqlStmt) {
      payload.sqlStmt = payload.sqlStmt.trim();
    }

    this.save.emit(payload);
  }

  onAddAndCreateAnother(): void {
    if (this.form.invalid) { this.form.markAllAsTouched(); this.cdr.markForCheck(); return; }

    // Trim all text fields before emitting
    const payload = this.form.value;
    if (payload.mappingName) {
      payload.mappingName = payload.mappingName.trim().toUpperCase();
    }
    if (payload.dataTableName) {
      payload.dataTableName = payload.dataTableName.trim();
    }
    if (payload.dataColumnName) {
      payload.dataColumnName = payload.dataColumnName.trim();
    }
    if (payload.whereClause) {
      payload.whereClause = payload.whereClause.trim();
    }
    if (payload.sqlStmt) {
      payload.sqlStmt = payload.sqlStmt.trim();
    }

    this.saveAndCreateAnother.emit(payload);
    // Reset form immediately for next entry
    this.resetForm();
  }
}
