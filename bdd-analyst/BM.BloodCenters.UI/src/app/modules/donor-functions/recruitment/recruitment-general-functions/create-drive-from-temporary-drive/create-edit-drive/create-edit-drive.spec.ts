// Helper function to fill valid form for onSubmit tests
function fillValidForm(component: CreateEditDriveComponent): void {
  const futureDate = new Date();
  futureDate.setFullYear(futureDate.getFullYear() + 1);

  component.driveForm.patchValue({
    driveId: 'DRV-TEST',
    driveDate: futureDate,
    driveType: 'M',
    category: 'ROUTN',
    recruiterId: 'REC001',
    startDate: futureDate,
    startTime: '09:00',
    endDate: futureDate,
    endTime: '17:00'
  });

  // Force form to be valid by clearing validators temporarily
  Object.keys(component.driveForm.controls).forEach(key => {
    component.driveForm.get(key)?.clearValidators();
    component.driveForm.get(key)?.updateValueAndValidity();
  });
  // Clear group-level validators too
  component.driveForm.clearValidators();
  component.driveForm.updateValueAndValidity();
}
