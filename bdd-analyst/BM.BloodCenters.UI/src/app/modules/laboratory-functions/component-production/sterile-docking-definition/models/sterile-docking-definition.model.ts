// Docking Types (from Oracle Forms RG_DOCK_TYPE)
export enum DockingType {
  BA = 'BA',  // Bag to Bag
  FI = 'FI',  // Filter
  SE = 'SE',  // Segment
  FB = 'FB',  // Filter to Bag
  NE = 'NE',  // Needle
  BF = 'BF'   // Bag to Filter
}

export interface DockingTypeOption {
  code: DockingType;
  description: string;
}

// Main configuration DTO - matching backend CreateSterileDockingDefinitionDto
export interface DockingConfigurationDto {
  // Required fields
  unitId: string;                    // Unit identifier (required)
  chapterId: string;                 // Chapter/Facility ID (required)
  collDate: string;                  // Collection date in YYYY-MM-DD format (required)
  itemInd: DockingType;              // Docking type (BA/FI/SE/FB/NE/BF) (required)

  // Optional fields
  sdcWsNumber?: string;              // Worksheet ID (auto-generated by backend if not provided)
  sterileMachine?: string;           // Machine code
  waferLotNumber?: string;           // Wafer lot number
  lotNumber?: string;                // Bag lot number
  numberOfItems?: number;            // Number of units
  weldFlag?: 'Y' | 'N';             // Weld OK flag (per unit)
  productCode?: string;              // Original product code (per unit)
  numberOfBags?: number;             // Number of bags
  componentPrefix?: string;          // Component prefix
  segmentRemFlag?: string;           // Segment removal flag
  segmentNumber?: string;            // Segment number
  programId?: string;                // Program ID (default: 'CPISDDFN')
  catalogNumber?: string;            // Catalog number (max 10 chars)
  filterType?: string;               // Filter type/catalog (max 30 chars)
  filterLotNumber?: string;          // Filter lot number (max 30 chars)
  attribCode?: string;               // Attribute code (max 10 chars)
  attribGroup?: string;              // Attribute group (max 5 chars)
  processDate?: string;              // Process date (ISO format)
  numberOfUnitsEntered?: number;     // Number of units to be entered
  oldProductCode?: string;           // Product code being docked/converted from
  newProductCode?: string;           // Product code being converted to (FB/BF)
}

// UI form data (used internally in the form, before mapping to API DTO)
export interface DockingConfigurationFormData {
  dockingType: DockingType;          // UI field: docking type
  description?: string;              // UI field: description (for validation only, not sent to API)
  machineCode: string;               // UI field: machine code
  waferLotNumber: string;            // UI field: wafer lot
  numberOfUnits: number;             // UI field: number of units
  bagCatalogNumber: string;          // UI field: catalog number (for validation only)
  bagLotNumber: string;              // UI field: bag lot number
  filterType?: string;               // UI field: filter type (for validation only)
  filterLotNumber?: string;          // UI field: filter lot (for validation only)
  numberOfComponents: number;        // UI field: number of components (for validation only)
  attributeCode: string;             // UI field: attribute code (for validation only)
  attributeDescription?: string;     // UI field: attribute description (read-only)
  processDate?: string;              // UI field: process date (read-only, display only)
}

// Complete configuration (combines DTO fields + form-only fields for display)
export interface DockingConfigurationComplete extends Partial<DockingConfigurationDto> {
  description?: string;
  bagCatalogNumber?: string;
  numberOfComponents?: number;
  attributeCode?: string;
  attributeDescription?: string;
  segmentRemFlag?: string;
  segmentNumber?: string;
  processDateDisplay?: string;
  productType?: string;
}

