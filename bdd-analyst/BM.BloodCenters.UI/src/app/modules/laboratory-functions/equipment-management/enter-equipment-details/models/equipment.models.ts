/**
 * Equipment Models
 * TypeScript interfaces derived from the EQIEQUIP API and FMB source.
 */

/**
 * Equipment DTO — matches the actual API response for GET/POST endpoints.
 * Display-name fields (equipTypeName, locationName, statusName) are NOT returned
 * by the API and must be derived from local dropdown data in the component.
 */
export interface EquipmentDto {
  equipType: string;
  equipId: string;
  equipReference: string;
  instId: string | null;
  chapterId: string | null;
  serialNumber: string | null;
  location: string | null;
  status: string | null;
  inServiceDate: string | null;
  outServiceDate: string | null;
  manufacturer: string | null;
  osokFlag: string | null;
  firstProductionDate: string | null;
  lastProductionDate: string | null;
  serviceContact: string | null;
  servicePhone: string | null;
  serviceStartDate: string | null;
  serviceEndDate: string | null;
  lastModifiedDate: string | null;
  modifiedBy: string | null;
  auditKey: number | null;
  programId: string | null;
}

/**
 * Create Equipment Request DTO — maps to POST /equipment.
 * ChapterId is set by the API from the user session (not sent in body).
 * EquipReference is auto-generated by the API as EQ-XXXXXX.
 */
export interface CreateEquipmentRequestDto {
  equipType: string;
  equipId: string;
  instId?: string | null;
  serialNumber?: string | null;
  location?: string | null;
  status: string;
  inServiceDate?: string | null;
  outServiceDate?: string | null;
  manufacturer?: string | null;
  osokFlag?: string | null;
  firstProductionDate: string;
  lastProductionDate?: string | null;
  serviceContact?: string | null;
  servicePhone?: string | null;
  serviceStartDate?: string | null;
  serviceEndDate?: string | null;
}

/**
 * Update Equipment Request DTO — maps to PUT /equipment/{equipType}/{equipId}/{equipReference}.
 */
export interface UpdateEquipmentRequestDto extends CreateEquipmentRequestDto {}

/**
 * Equipment Query DTO — body for POST /equipment/{take}/{skip}.
 */
export interface EquipmentQueryDto {
  equipType?: string | null;
  equipId?: string | null;
  equipReference?: string | null;
  status?: string | null;
  chapterId?: string | null;
  location?: string | null;
  searchKeyword?: string | null;
  sortColumn?: string | null;
  sortOrder?: 'ASC' | 'DESC' | null;
}

/**
 * Dropdown Option for form select controls.
 */
export interface DropdownOption {
  value: string;
  label: string;
  description?: string;
}

/**
 * Configurable Equipment Detail row in the details grid.
 */
export interface ConfigurableEquipmentDetail {
  sequence: number;
  detail: string;
  value: string | null;
}

/**
 * Equipment form value — matches the reactive FormGroup controls.
 * Date fields use moment objects (from ChapterAwareDateAdapter) and are
 * converted to ISO strings before sending to the API.
 */
export interface EquipmentFormValue {
  // Selection card
  equipType: string | null;
  equipId: string | null;
  equipRef: string | null;
  // Details
  instId: string | null;
  status: string | null;
  serialNumber: string | null;
  location: string | null;
  inServiceDate: any | null;
  outServiceDate: any | null;
  firstProductionDate: any | null;
  lastProductionDate: any | null;
  manufacturer: string | null;
  exportFlag: string | null;
  serviceContact: string | null;
  servicePhone: string | null;
  serviceStartDate: any | null;
  serviceEndDate: any | null;
}

/**
 * Standard API response wrapper.
 */
export interface ApiResponse<T = any> {
  success: boolean;
  statusCode: number;
  message: string;
  data?: T;
  item?: T;
  total?: number;
  totalCount?: number;
  errorResponse?: {
    errorCode?: string;
    error: string;
  };
}

/**
 * Error response structure.
 */
export interface ErrorResponse {
  success: false;
  statusCode: number;
  errorCode?: string;
  errorResponse?: {
    errorCode?: string;
    error: string;
  };
  message?: string;
}
