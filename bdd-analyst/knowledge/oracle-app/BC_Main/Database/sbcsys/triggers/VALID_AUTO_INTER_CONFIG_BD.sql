--------------------------------------------------------
--  DDL for Trigger VALID_AUTO_INTER_CONFIG_BD
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE TRIGGER "VALID_AUTO_INTER_CONFIG_BD" 
BEFORE DELETE
ON SBCSYS.VALID_AUTO_INTER_CONFIG
REFERENCING NEW AS NEW OLD AS OLD
FOR EACH ROW
begin

	insert into VALID_AUTO_INTER_CONFIG_AUDIT
    (
        CHAPTER_ID, ACTION_FUNCTION_NAME, ACTION_TYPE,
        ACTION_CODE, ACTION_PRODUCT_CODE, INTER_ON_CURRENT_PROD,
        INTER_ON_OTHER_PRODS, INTER_ON_OTHER_PROD_TYPES, INTER_ON_UNIT_LEVEL,
        INTER_ALL_PROD_BUT_CURR, INTER_CODE,AUDIT_KEY,
	PROGRAM_ID,INSERT_DATE, INSERT_USER, EFF_DATE, TERM_DATE,
	AUDIT_USER,AUDIT_DATE
    )
    values
    (
        :old.CHAPTER_ID, :old.ACTION_FUNCTION_NAME, :old.ACTION_TYPE,
        :old.ACTION_CODE, :old.ACTION_PRODUCT_CODE, :old.INTER_ON_CURRENT_PROD,
	:old.INTER_ON_OTHER_PRODS, :old.INTER_ON_OTHER_PROD_TYPES, :old.INTER_ON_UNIT_LEVEL,
        :old.INTER_ALL_PROD_BUT_CURR,:old.INTER_CODE, :old.AUDIT_KEY,
	:old.PROGRAM_ID,:old.INSERT_DATE, :old.INSERT_USER, :old.EFF_DATE, :old.TERM_DATE,
	lt_user_session.get_userid, sysdate
    );
end;
/
ALTER TRIGGER "VALID_AUTO_INTER_CONFIG_BD" ENABLE;
