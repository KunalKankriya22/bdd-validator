--------------------------------------------------------
--  DDL for Trigger CUSTOMER_PREFERRED_TIERS_BD
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE TRIGGER "CUSTOMER_PREFERRED_TIERS_BD" before delete
on CUSTOMER_PREFERRED_TIERS for each row
begin
  insert into CUSTOMER_PREFERRED_TIERS_AUDIT
  (	CHAPTER_ID,
	CUSTOMER_ID,
	PRODUCT_TYPE,
	TIER,
	ALTERNATE_TIER_FLAG,
	EFF_DATE,
	TERM_DATE,
	LAST_MODIFIED_DATE,
	AUDIT_KEY,
	PROGRAM_ID,
	AUDIT_INSERT_USER,
	AUDIT_INSERT_DATE
  )
  values
  (	:old.CHAPTER_ID,
	:old.CUSTOMER_ID,
	:old.PRODUCT_TYPE,
	:old.TIER,
	:old.ALTERNATE_TIER_FLAG,
	:old.EFF_DATE,
	:old.TERM_DATE,
	:old.LAST_MODIFIED_DATE,
	:old.AUDIT_KEY,
	'DELETE',LT_USER_SESSION.GET_USERID,
    sysdate
  ) ;
end ;
/
ALTER TRIGGER "CUSTOMER_PREFERRED_TIERS_BD" ENABLE;
