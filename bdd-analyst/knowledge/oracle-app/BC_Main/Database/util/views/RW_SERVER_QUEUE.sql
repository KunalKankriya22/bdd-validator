CREATE OR REPLACE FORCE EDITIONABLE VIEW "UTIL"."RW_SERVER_QUEUE" ( "JOB_TYPE",
"JOB_ID",
"JOB_NAME",
"STATUS_CODE",
"STATUS_MESSAGE",
"COMMAND_LINE",
"OWNER",
"DESTYPE",
"DESNAME",
"SERVER",
"QUEUED",
"STARTED",
"FINISHED",
"LAST_RUN",
"NEXT_RUN",
"REPEAT_INTERVAL",
"REPEAT_PATTERN",
"CACHE_KEY",
"CACHE_HIT" ) AS
    SELECT
        job_queue                  job_type,
        job_id,
        job_name,
        status_code,
        status_message,
        command_line,
        owner,
        destype,
        desname,
        server,
        queued,
        started,
        finished,
        last_run,
        next_run,
        repeat_interval,
        repeat_pattern,
        cache_key,
        decode(cache_hit, 0, 0, 1) cache_hit
    FROM
        rw_server_job_queue;