--------------------------------------------------------
--  DDL for Trigger CNF_EXTRACT_BI
--------------------------------------------------------

  CREATE OR REPLACE EDITIONABLE TRIGGER "CNF_EXTRACT_BI" 
BEFORE INSERT
ON CNF_EXTRACT
FOR EACH ROW
BEGIN
  IF :NEW.PROGRAM_ID IS NULL THEN
    :NEW.PROGRAM_ID := 'MANUAL';
  END IF;
  IF :NEW.INSERT_USER IS NULL THEN
     SELECT LT_USER_SESSION.GET_USERID INTO :NEW.INSERT_USER
       FROM DUAL ;
  END IF;
  IF :NEW.INSERT_DATE IS NULL THEN
     :NEW.INSERT_DATE := SYSDATE;
  END IF;
  IF :NEW.AUDIT_KEY IS NULL THEN
     SELECT AUDIT_SEQ_LAB.NEXTVAL INTO :NEW.AUDIT_KEY FROM DUAL;
  END IF;
END ;
/
ALTER TRIGGER "CNF_EXTRACT_BI" ENABLE;
