CREATE OR REPLACE FORCE EDITIONABLE VIEW "SBCSYS"."FRM50_ENABLED_ROLES" ( "ROLE",
"FLAG" ) AS
    SELECT
        urp.granted_role       role,
        SUM(DISTINCT decode(rrp.granted_role, 'ORAFORMS$OSC', 2, 'ORAFORMS$BGM', 4,
                            'ORAFORMS$DBG', 1, 0)) flag
    FROM
        sys.user_role_privs urp,
        role_role_privs     rrp
    WHERE
            urp.granted_role = rrp.role (+)
        AND urp.granted_role NOT LIKE 'ORAFORMS$%'
    GROUP BY
        urp.granted_role;

