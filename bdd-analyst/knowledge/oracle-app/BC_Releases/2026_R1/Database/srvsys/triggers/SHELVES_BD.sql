	LAST_MODIFIED_DATE,
	TERM_DATE,
	AUDIT_KEY,
	PROGRAM_ID,
	AUDIT_INSERT_USER,
	AUDIT_INSERT_DATE
  )
  values
  (	:old.CHAPTER_ID,
	:old.WAREHOUSE_ID,
	:old.DEVICE_TYPE,
	:old.DEVICE_NUMBER,
	:old.RACK_NUMBER,
	:old.SHELF_NUMBER,
	:old.SHELF_DESCRIPTION,
	:old.SHELF_TRAY_COUNT,
	:old.EFFECTIVE_DATE,
	:old.LAST_MODIFIED_DATE,
	:old.TERM_DATE,
	:old.AUDIT_KEY,
