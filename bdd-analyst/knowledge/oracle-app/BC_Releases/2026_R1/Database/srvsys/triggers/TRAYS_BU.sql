  CREATE OR REPLACE EDITIONABLE TRIGGER "TRAYS_BU" before update
of  CHAPTER_ID,
	WAREHOUSE_ID,
	DEVICE_TYPE,
	DEVICE_NUMBER,
	RACK_NUMBER,
	SHELF_NUMBER,
	TRAY_NUMBER,
	TRAY_DESCRIPTION,
	TRAY_STATUS,
	EFFECTIVE_DATE,
	LAST_MODIFIED_DATE,
	TERM_DATE
on trays
