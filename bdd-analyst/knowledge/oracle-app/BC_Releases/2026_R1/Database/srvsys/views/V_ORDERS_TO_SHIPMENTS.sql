CREATE OR REPLACE FORCE EDITIONABLE VIEW "SRVSYS"."V_ORDERS_TO_SHIPMENTS" ( "CHAPTER_ID",
"ORDER_NO",
"PICK_SLIP_ID",
"BOX_ID",
"SHIPMENT_NO" ) AS
    SELECT DISTINCT
        ord.chapter_id   chapter_id,
        ord.order_no     order_no,
        psp.pick_slip_id pick_slip_id,
        bx.box_id        box_id,
        sh.shipment_no   shipment_no
    FROM
        shipments          sh,
        boxes              bx,
        pick_slip_products psp,
        pick_slips         ps,
        orders             ord
    WHERE
            sh.shipment_no (+) = bx.shipment_no
        AND bx.box_id (+) = psp.box_id
        AND psp.pick_slip_id (+) = ps.pick_slip_id
        AND ps.order_no (+) = ord.order_no
        AND ord.order_status NOT IN ( 'CL', 'CA', 'SY', 'HO', 'PE' )
    GROUP BY
        ord.chapter_id,
        ord.order_no,
        psp.pick_slip_id,
        bx.box_id,
        sh.shipment_no;

